import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

// Run against a fresh temporary database, never the user's wardrobe.
const directory=await mkdtemp(path.join(tmpdir(),'divara-assistant-'));
const root=fileURLToPath(new URL('../',import.meta.url));
process.env.DATABASE_URL=`file:${path.join(directory,'test.db')}`;
process.env.JWT_SECRET='assistant-regression-test-secret';
process.env.LOCAL_CLASSIFIER_ENABLED='false';
process.env.ASSISTANT_MODEL_ENABLED='false';
process.env.AUTO_ANALYZE_UPLOADS='false';
let server,prisma;
try {
 await writeFile(path.join(directory,'test.db'),'');
 execFileSync(process.execPath,[path.join(root,'node_modules/prisma/build/index.js'),'migrate','deploy','--schema',path.join(root,'prisma/schema.prisma')],{cwd:root,env:process.env,stdio:'pipe'});
 const {createApp}=await import('../src/app.ts');
 ({prisma}=await import('../src/lib/db.ts'));
 const {respond}=await import('../src/scoring/assistant.ts');
 const {canonicalColor}=await import('../src/scoring/score.ts');
 const {SAMPLE_ITEMS}=await import('../src/data/samples.ts');
 server=createApp().listen(0,'127.0.0.1');
 await new Promise((resolve,reject)=>{server.once('listening',resolve);server.once('error',reject);});
 const base=`http://127.0.0.1:${server.address().port}/api`;
 let cookie;
 async function call(url,body,expected=200) {
  const response=await fetch(base+url,{method:body?'POST':'GET',headers:{...(cookie?{Cookie:cookie}:{}),'Content-Type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});
  const data=await response.json();
  assert.equal(response.status,expected,JSON.stringify(data));
  return {data,response};
 }
 await call('/assistant',{message:'What should I wear?'},401);
 const registration=await call('/auth/register',{name:'Assistant test',email:'assistant@example.test',password:'Assistant-test-2026!'},201);
 cookie=registration.response.headers.get('set-cookie').split(';')[0];
 const userId=registration.data.user.id;
 const {data:knowledge}=await call('/scoring/knowledge');
 const item=(id,key,color)=>{const g=knowledge.garments.find(g=>g.key===key);return {item_id:id,product_name:`${color} ${g.title}`,subcategory:g.title,category:g.category,color,style:'Formal',owned:true,laundry_status:'clean'};};
 const fixture=[item('ivory-shirt','shirt','Ivory'),item('blue-shirt','shirt','Blue'),item('red-shirt','shirt','Red'),item('trousers','trousers','Black'),item('loafers','loafers','Charcoal')];
 const prefs={colors:['Ivory']};
 const first=respond('What should I wear for a wedding?',fixture,knowledge,prefs);
 assert.equal(first.state.context.occasion,'Wedding');
 assert.equal(first.items.find(i=>i.category==='Tops').item_id,'ivory-shirt');
 const changed=respond('change the shirt',fixture,knowledge,prefs,first.state);
 assert.equal(changed.items.length,first.items.length);
 assert.notEqual(changed.state.targetId,'ivory-shirt');
 const unchanged=(reply)=>reply.items.filter(i=>i.category!=='Tops').map(i=>i.item_id);
 assert.deepEqual(unchanged(changed),unchanged(first));
 const red=respond('change it to red',fixture,knowledge,prefs,changed.state);
 assert.equal(canonicalColor(red.items.find(i=>i.category==='Tops').color),'red');
 assert.deepEqual(unchanged(red),unchanged(first));
 assert.equal(red.state.context.occasion,'Wedding');
 assert.equal(typeof red.score,'number');
 const unavailable=respond('change it to red',fixture.filter(i=>i.item_id!=='red-shirt'),knowledge,prefs,changed.state);
 assert.match(unavailable.note,/No suitable red/);
 assert.deepEqual(unavailable.items,changed.items);
 const laundry=respond('change it to red',fixture.map(i=>i.item_id==='red-shirt'?{...i,laundry_status:'in-laundry'}:i),knowledge,prefs,changed.state);
 assert.deepEqual(laundry.items,changed.items);
 const redBlouse=respond('change it to red',[...fixture.filter(i=>i.item_id!=='red-shirt'),item('red-blouse','blouse','Red')],knowledge,prefs,changed.state);
 assert.deepEqual(redBlouse.items,changed.items,'Pronoun must still refer to a shirt');
 assert.match(respond('change it to red',fixture,knowledge,prefs,first.state).note,/Which piece/);
 assert.match(respond('change the dress',fixture,knowledge,prefs,first.state).note,/missing or ambiguous/);
 assert.match(respond('change the shirt to red and blue',fixture,knowledge,prefs,first.state).note,/one colour/);
 const stale=respond('change the shirt',fixture.filter(i=>i.item_id!=='ivory-shirt'),knowledge,prefs,first.state);
 assert.equal(stale.items.length,0);
 const colorQuestion=respond('Does this color suit my outfit?',fixture,knowledge,prefs,first.state);
 assert.deepEqual(colorQuestion.items,first.items);
 const top=respond('change the top',fixture,knowledge,prefs,first.state);
 assert.notEqual(top.items[0].item_id,first.items[0].item_id);
 const footwear=respond('change the shoes',[...fixture,item('other-shoes','loafers','Navy')],knowledge,prefs,first.state);
 assert.equal(footwear.items.find(i=>i.category==='Shoes').item_id,'other-shoes');
 assert.deepEqual(footwear.items.filter(i=>i.category!=='Shoes'),first.items.filter(i=>i.category!=='Shoes'));
 assert.match(respond('change the shirt and shoes',fixture,knowledge,prefs,first.state).note,/one piece at a time/);
 assert.deepEqual(respond('change it to magenta',fixture,knowledge,prefs,changed.state).items,changed.items);
 assert.equal(respond('what should I wear for a wedding in cold weather?',fixture,knowledge,prefs).items.length,0,'Do not invent a warm layer');
 const add=async(key,color)=>(await call('/items',{...item('unused',key,color),colorHex:'#333333'},201)).data.item;
 const ownedWhite=await add('shirt','White');
 const ownedRed=await add('shirt','Red');
 const ownedBottom=await add('trousers','Black');
 const ownedShoes=await add('loafers','Black');
 // Simulate an already recognised camera piece, using the same saved item path.
 const upload=await prisma.upload.create({data:{userId,filename:'assistant-camera.png',mimeType:'image/png',size:1}});
 const photo=await prisma.wardrobePhoto.create({data:{userId,uploadId:upload.id,imageHash:'a'.repeat(64),source:'camera',importedAt:new Date()}});
 await prisma.clothingItem.update({where:{id:ownedRed.item_id},data:{photoId:photo.id,imageUrl:'/uploads/assistant-camera.png'}});
 const state={itemIds:[ownedWhite.item_id,ownedBottom.item_id,ownedShoes.item_id],context:{occasion:'Wedding',weather:'Any',styles:['Formal']},targetId:ownedWhite.item_id};
 const {data:cameraReply}=await call('/assistant',{message:'change it to red',state});
 assert.equal(cameraReply.items[0].item_id,ownedRed.item_id);
 assert.equal(cameraReply.items[0].photo_id,photo.id);
 assert.equal(cameraReply.items[0].image_url,'/uploads/assistant-camera.png');
 assert.deepEqual(cameraReply.items.slice(1).map(i=>i.item_id),state.itemIds.slice(1));
 assert.equal(cameraReply.state.context.occasion,'Wedding');
 assert.ok(cameraReply.assessmentId,'Chat outfit scores are persisted');
 const {data:initial}=await call('/assistant',{message:'what should I wear for a wedding?'});
 const allowed=new Set([...SAMPLE_ITEMS.map(i=>i.item_id),ownedWhite.item_id,ownedRed.item_id,ownedBottom.item_id,ownedShoes.item_id]);
 assert.ok(initial.items.length);
 assert.ok(initial.items.every(i=>allowed.has(i.item_id)));
 assert.ok(cameraReply.items.some(i=>i.owned),'Saved clothes participate in wardrobe selection');
 const {data:samples}=await call('/items/samples');
 assert.deepEqual(samples.items.map(i=>i.item_id),SAMPLE_ITEMS.map(i=>i.item_id),'UI and backend use the same sample wardrobe');
 const {data:next}=await call('/assistant',{message:'what should I wear for a wedding?'});
 const mains=reply=>reply.items.filter(i=>['Tops','Bottoms','Dresses'].includes(i.category)).map(i=>`${i.subcategory}:${canonicalColor(i.color)}`).sort().join('|');
 assert.notEqual(mains(next),mains(initial),'Fresh chats use saved recommendation history');
 await call('/assistant',{message:'',state},400);
 await call('/assistant',{message:'change it to red',state:{...state,context:{...state.context,occasion:'fake'}}},400);
 // A second account cannot resolve the first account's item IDs.
 const second=await call('/auth/register',{name:'Second',email:'second@example.test',password:'Assistant-test-2026!'},201);
 cookie=second.response.headers.get('set-cookie').split(';')[0];
 const {data:isolated}=await call('/assistant',{message:'change it to red',state});
 assert.equal(isolated.items.length,0);
 assert.match(isolated.note,/no longer available/);
 console.log('PASS: wedding → shirt replacement → red; other pieces unchanged; missing colours; laundry; ambiguity; shirt type preserved; deleted items; colour questions; cold-weather constraints; camera clothes; samples + saved wardrobe; authentication, validation and account isolation.');
} finally {
 if(server)await new Promise(resolve=>server.close(resolve));
 if(prisma)await prisma.$disconnect();
 await rm(directory,{recursive:true,force:true});
}
